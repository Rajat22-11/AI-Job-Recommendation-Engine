// Dev seed: inserts ~40 clearly marked sample jobs ("[Sample]", dedupe_key "seed:N").
// Data only — never touches the schema. Safe to re-run (upserts).
//
//   pnpm seed         insert or refresh sample jobs
//   pnpm seed:clean   delete every sample job and its links/applications
//
// Dev and production share one database, so sample jobs show up in production
// too. Run `pnpm seed:clean` before relying on real data.

import { createClient } from "@supabase/supabase-js";
import type { Database } from "../src/lib/db/database.types";
import {
  LOCATION_BUCKETS,
  ROLE_TRACKS,
  WORK_MODES,
  type LocationBucket,
  type RoleTrack,
} from "../src/lib/db/domain";

const COUNT = 40;
const SEED_PREFIX = "seed:";
const HOUR_MS = 60 * 60 * 1000;

function fail(message: string): never {
  console.error(message);
  process.exit(1);
}

if (process.env.NODE_ENV === "production") {
  fail("Refusing to seed with NODE_ENV=production.");
}
const url = process.env.SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!url || !key)
  fail("Set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY in .env.local.");

const db = createClient<Database>(url, key, {
  auth: { persistSession: false, autoRefreshToken: false },
});

